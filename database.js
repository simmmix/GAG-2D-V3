const fs = require('fs');
const path = require('path');

function postgresConnectionString(value) {
    let url;
    try {
        url = new URL(value);
    } catch {
        throw new Error('DATABASE_URL musí obsahovat platnou adresu PostgreSQL.');
    }
    if (!['postgres:','postgresql:'].includes(url.protocol)) {
        throw new Error('DATABASE_URL musí začínat postgres:// nebo postgresql://.');
    }
    const local = ['localhost','127.0.0.1','[::1]'].includes(url.hostname);
    if (!local) url.searchParams.set('sslmode','verify-full');
    return url.toString();
}

function preparedApi(query) {
    return {
        prepare(sql) {
            return {
                all: (...args) => query(sql,args),
                get: async (...args) => (await query(sql,args))[0],
                run: (...args) => query(sql,args)
            };
        },
        exec: sql => query(sql,[])
    };
}

function createPostgres(url) {
    const {Pool} = require('pg');
    const pool = new Pool({
        connectionString:postgresConnectionString(url),
        max:4,
        connectionTimeoutMillis:15000,
        idleTimeoutMillis:20000
    });
    pool.on('error',() => console.error('Databázové připojení se přerušilo. Další požadavek se připojí znovu.'));
    const connection = client => preparedApi(async (sql,args) => {
        let parameter = 0;
        const converted = sql.replace(/\?/g,() => '$' + ++parameter);
        const result = await client.query(converted,args);
        return result.rows || [];
    });
    return {
        ...connection(pool),
        postgres:true,
        async transaction(work) {
            const client = await pool.connect();
            try {
                await client.query('BEGIN');
                const result = await work(connection(client));
                await client.query('COMMIT');
                return result;
            } catch (error) {
                await client.query('ROLLBACK').catch(() => {});
                throw error;
            } finally {
                client.release();
            }
        },
        close:() => pool.end()
    };
}

function createSqlite(filename) {
    const Database = require('better-sqlite3');
    fs.mkdirSync(path.dirname(filename),{recursive:true});
    const sqlite = new Database(filename);
    let previous = Promise.resolve();
    const queued = work => {
        const result = previous.then(work);
        previous = result.catch(() => {});
        return result;
    };
    const execute = (sql,args) => {
        const statement = sqlite.prepare(sql);
        if (statement.reader) return statement.all(...args);
        statement.run(...args);
        return [];
    };
    const inTransaction = {...preparedApi(async (sql,args) => execute(sql,args)),exec:async sql => sqlite.exec(sql)};
    return {
        ...preparedApi((sql,args) => queued(() => execute(sql,args))),
        exec:sql => queued(() => sqlite.exec(sql)),
        postgres:false,
        transaction:work => queued(async () => {
            sqlite.exec('BEGIN IMMEDIATE');
            try {
                const result = await work(inTransaction);
                sqlite.exec('COMMIT');
                return result;
            } catch (error) {
                sqlite.exec('ROLLBACK');
                throw error;
            }
        }),
        close:() => queued(() => sqlite.close())
    };
}

// Shodné porovnání písmen A–Z v obou databázích. Jména s diakritikou ze staršího SQLite zůstanou platná.
const postgresName = value => `translate(${value}, 'ABCDEFGHIJKLMNOPQRSTUVWXYZ', 'abcdefghijklmnopqrstuvwxyz')`;
function nameMatches(db) {
    return db.postgres ? postgresName('username') + ' = ' + postgresName('?') : 'username = ? COLLATE NOCASE';
}

async function initialize(db) {
    const userIdentity = db.postgres ? 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' : 'INTEGER PRIMARY KEY';
    const chatIdentity = db.postgres ? userIdentity : 'INTEGER PRIMARY KEY AUTOINCREMENT';
    const usernameConstraint = db.postgres ? '' : ' UNIQUE COLLATE NOCASE';
    const scoreType = db.postgres ? 'DOUBLE PRECISION' : 'REAL';

    await db.transaction(async tx => {
        if (db.postgres) await tx.exec('SELECT pg_advisory_xact_lock(427171)');
        await tx.exec(`
            CREATE TABLE IF NOT EXISTS users (
                id ${userIdentity},
                username TEXT NOT NULL${usernameConstraint},
                password TEXT NOT NULL,
                token TEXT,
                selected_garden TEXT,
                coins ${scoreType} DEFAULT 0,
                gems ${scoreType} DEFAULT 0,
                level ${scoreType} DEFAULT 1
            );
            CREATE TABLE IF NOT EXISTS chat_messages (
                id ${chatIdentity},
                user_id INTEGER NOT NULL REFERENCES users(id),
                body TEXT NOT NULL,
                created_at BIGINT NOT NULL,
                recipient_id INTEGER REFERENCES users(id)
            );
            CREATE TABLE IF NOT EXISTS player_presence (
                user_id INTEGER PRIMARY KEY REFERENCES users(id),
                token TEXT NOT NULL,
                seen_at BIGINT NOT NULL
            );
            CREATE TABLE IF NOT EXISTS seed_gifts (
                id TEXT PRIMARY KEY,
                user_id INTEGER NOT NULL REFERENCES users(id),
                seed TEXT NOT NULL,
                amount INTEGER NOT NULL,
                created_at BIGINT NOT NULL
            );
            CREATE TABLE IF NOT EXISTS account_bans (
                user_id INTEGER PRIMARY KEY REFERENCES users(id),
                banned_at BIGINT NOT NULL
            );
            CREATE TABLE IF NOT EXISTS wallet_changes (
                id ${chatIdentity},
                receipt TEXT NOT NULL UNIQUE,
                user_id INTEGER NOT NULL REFERENCES users(id),
                currency TEXT NOT NULL CHECK (currency IN ('coins','gems')),
                amount BIGINT NOT NULL CHECK (amount BETWEEN 0 AND 1000000000000000)
            );
            CREATE INDEX IF NOT EXISTS wallet_changes_by_user ON wallet_changes(user_id,id);
            CREATE TABLE IF NOT EXISTS account_progress (
                user_id INTEGER PRIMARY KEY REFERENCES users(id),
                version INTEGER NOT NULL,
                payload TEXT NOT NULL
            );
            CREATE INDEX IF NOT EXISTS users_by_token ON users(token);
            CREATE INDEX IF NOT EXISTS seed_gifts_by_user ON seed_gifts(user_id, created_at);
            CREATE INDEX IF NOT EXISTS chat_messages_by_user ON chat_messages(user_id, id);
        `);
        if (db.postgres) {
            await tx.exec(`
                ALTER TABLE chat_messages ADD COLUMN IF NOT EXISTS recipient_id INTEGER REFERENCES users(id);
                CREATE UNIQUE INDEX IF NOT EXISTS gag_users_by_name ON users (${postgresName('username')});
            `);
        } else if (!(await tx.prepare('PRAGMA table_info(chat_messages)').all()).some(column => column.name === 'recipient_id')) {
            await tx.exec('ALTER TABLE chat_messages ADD COLUMN recipient_id INTEGER REFERENCES users(id)');
        }
    });
}

function createDatabase({url = process.env.DATABASE_URL, sqlitePath} = {}) {
    if (url) return createPostgres(url);
    const folder = process.env.GAG_DATA_DIR ? path.resolve(process.env.GAG_DATA_DIR) : __dirname;
    return createSqlite(sqlitePath || path.join(folder,'gag2d.sqlite'));
}

module.exports = {createDatabase, initialize, nameMatches};
